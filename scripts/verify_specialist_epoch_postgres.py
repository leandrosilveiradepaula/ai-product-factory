#!/usr/bin/env python3
"""Disposable PostgreSQL 16 regression for specialist Pause/Resume and lease tokens.

Refuses any non-local or non-dedicated test database. Never calls GitHub,
Vercel, a model, n8n, or the production Control Plane.
"""
import json
import os
from pathlib import Path
import psycopg
from psycopg.conninfo import conninfo_to_dict

dsn=os.environ.get("FACTORY_SPECIALIST_EPOCH_TEST_DSN","")
info=conninfo_to_dict(dsn)
if (os.environ.get("FACTORY_SPECIALIST_EPOCH_TEST_ISOLATED")!="true"
    or info.get("host") not in ("127.0.0.1","localhost")
    or info.get("dbname")!="factory_specialist_epoch_test"):
    raise SystemExit("REFUSING_NON_ISOLATED_SPECIALIST_EPOCH_DATABASE")

root=Path(__file__).resolve().parents[1]
migration=(root/"supabase/migrations/20261021030000_fence_specialist_epoch_and_lease_token.sql").read_text()
schema="""
CREATE TABLE public.factory_projects(
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 project_key text NOT NULL UNIQUE,
 repository text NOT NULL DEFAULT 'owner/repo',
 manifest jsonb NOT NULL DEFAULT '{}'::jsonb,
 is_active boolean NOT NULL DEFAULT true);
CREATE TABLE public.factory_project_execution_controls(
 project_id uuid PRIMARY KEY REFERENCES public.factory_projects(id),
 state text NOT NULL,generation bigint NOT NULL);
CREATE TABLE public.factory_tasks(
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 project_id uuid NOT NULL REFERENCES public.factory_projects(id));
CREATE TABLE public.factory_runs(
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 task_id uuid NOT NULL REFERENCES public.factory_tasks(id),
 candidate_commit text,status text NOT NULL,metadata jsonb NOT NULL DEFAULT '{}'::jsonb);
CREATE TABLE public.factory_execution_team_plans(
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 project_id uuid NOT NULL REFERENCES public.factory_projects(id),
 version int NOT NULL,status text NOT NULL,plan jsonb NOT NULL);
CREATE TABLE public.factory_specialist_lane_jobs(
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 run_id uuid NOT NULL REFERENCES public.factory_runs(id),
 project_id uuid NOT NULL REFERENCES public.factory_projects(id),
 role text NOT NULL,candidate_commit text NOT NULL,status text NOT NULL DEFAULT 'queued',
 required boolean NOT NULL DEFAULT true,attempt_count integer NOT NULL DEFAULT 0,
 lease_owner text,lease_expires_at timestamptz,
 findings jsonb NOT NULL DEFAULT '[]'::jsonb,evidence jsonb NOT NULL DEFAULT '{}'::jsonb,
 created_at timestamptz NOT NULL DEFAULT now(),updated_at timestamptz NOT NULL DEFAULT now(),
 completed_at timestamptz,
 UNIQUE(run_id,role,candidate_commit));
CREATE TABLE public.factory_evaluations(
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 run_id uuid NOT NULL REFERENCES public.factory_runs(id),
 eval_type text NOT NULL,status text NOT NULL,baseline_ref text,
 result jsonb NOT NULL DEFAULT '{}'::jsonb);
CREATE TABLE public.factory_audit_events(
 id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
 project_id uuid,task_id uuid,run_id uuid,
 actor_type text NOT NULL,actor_ref text,event_type text NOT NULL,
 payload jsonb NOT NULL DEFAULT '{}'::jsonb);
CREATE OR REPLACE FUNCTION public.factory_assert_project_running(p_project_id uuid)
RETURNS void LANGUAGE plpgsql SET search_path TO '' AS $body$
DECLARE v_gen bigint;
BEGIN
  SELECT c.generation INTO v_gen
    FROM public.factory_project_execution_controls c
    JOIN public.factory_projects p ON p.id=c.project_id
    WHERE c.project_id=p_project_id AND p.is_active=true
      AND c.state='running' AND c.generation>0 FOR SHARE OF c,p;
  IF NOT FOUND THEN RAISE EXCEPTION 'project not running' USING errcode='PT409'; END IF;
END;
$body$;
"""

with psycopg.connect(dsn,autocommit=True) as conn:
    conn.execute(schema)
    conn.execute(migration)

    def one(sql,args=()):
        return conn.execute(sql,args).fetchone()[0]

    def project(name,state="running",generation=1):
        pid=one("INSERT INTO public.factory_projects(project_key) VALUES (%s) RETURNING id",(name,))
        conn.execute("INSERT INTO public.factory_project_execution_controls VALUES (%s,%s,%s)",(pid,state,generation))
        plan={"selected_agents":[{"role":"security"}]}
        conn.execute("INSERT INTO public.factory_execution_team_plans(project_id,version,status,plan) VALUES (%s,1,'ready',%s::jsonb)",(pid,json.dumps(plan)))
        return pid

    def run(pid,gen=1):
        tid=one("INSERT INTO public.factory_tasks(project_id) VALUES (%s) RETURNING id",(pid,))
        rid=one("INSERT INTO public.factory_runs(task_id,candidate_commit,status,metadata) VALUES (%s,%s,'ci_pending',%s::jsonb) RETURNING id",(tid,"a"*40,json.dumps({"execution_generation":gen})))
        return rid

    def enqueue(rid):
        return one("SELECT public.factory_enqueue_specialist_lanes(%s)",(rid,))

    def claim(worker):
        return one("SELECT public.factory_claim_specialist_lane('security',%s,600)",(worker,))

    def complete(job,token,status="passed"):
        proof={"candidate_commit":"a"*40,"_factory_claim_token":token,"model_call":False}
        return one("SELECT public.factory_complete_specialist_lane(%s,%s,'[]'::jsonb,%s::jsonb)",(job,status,json.dumps(proof)))

    def recover():
        return one("SELECT public.factory_recover_specialist_lanes(3)")

    def job_status(rid):
        return one("SELECT status FROM public.factory_specialist_lane_jobs WHERE run_id=%s",(rid,))

    def assert_rejected(f,sqlstate="PT409"):
        try:
            f()
            raise AssertionError("untrusted or revoked operation unexpectedly succeeded")
        except psycopg.Error as exc:
            assert exc.sqlstate==sqlstate,(exc.sqlstate,str(exc))

    # A paused older project cannot stop a new project from claiming a lane.
    pausable=project("paused-prefix")
    old_run=run(pausable)
    assert enqueue(old_run)["created_jobs"]==1
    conn.execute("UPDATE public.factory_project_execution_controls SET state='paused' WHERE project_id=%s",(pausable,))
    ready=project("independent-running")
    ready_run=run(ready)
    assert enqueue(ready_run)["created_jobs"]==1
    independent=claim("worker-independent")
    assert independent["run_id"]==str(ready_run),independent
    assert independent["execution_generation"]==1
    assert len(independent["claim_token"])==36
    assert_rejected(lambda: complete(independent["job_id"],"bad"))
    assert one("SELECT count(*) FROM public.factory_evaluations")==0
    done=complete(independent["job_id"],independent["claim_token"])
    assert done["status"]=="passed"
    assert job_status(ready_run)=="passed"
    assert one("SELECT count(*) FROM public.factory_evaluations WHERE run_id=%s",(ready_run,))==1
    assert_rejected(lambda: complete(independent["job_id"],independent["claim_token"]))
    assert one("SELECT count(*) FROM public.factory_evaluations WHERE run_id=%s",(ready_run,))==1

    # Operator resumes a project with queued, old-generation specialist work.
    conn.execute("UPDATE public.factory_project_execution_controls SET state='running',generation=2 WHERE project_id=%s",(pausable,))
    assert claim("worker-stale-only") is None
    result=recover()
    assert result["blocked"]==1,result
    assert job_status(old_run)=="blocked"
    assert one("SELECT count(*) FROM public.factory_audit_events WHERE event_type='specialist.lane.epoch_quarantined'")==1
    recover()
    assert one("SELECT count(*) FROM public.factory_audit_events WHERE event_type='specialist.lane.epoch_quarantined'")==1
    new_old_run=run(pausable,1)
    assert_rejected(lambda: enqueue(new_old_run))
    assert one("SELECT count(*) FROM public.factory_specialist_lane_jobs WHERE run_id=%s",(new_old_run,))==0

    # A claimed lane observed before Pause cannot complete after Resume.
    raced=project("claimed-before-pause")
    raced_run=run(raced)
    enqueue(raced_run)
    claimed=claim("worker-before-pause")
    assert claimed["run_id"]==str(raced_run)
    conn.execute("UPDATE public.factory_project_execution_controls SET state='paused' WHERE project_id=%s",(raced,))
    assert_rejected(lambda: complete(claimed["job_id"],claimed["claim_token"]))
    assert job_status(raced_run)=="claimed"
    conn.execute("UPDATE public.factory_project_execution_controls SET state='running',generation=2 WHERE project_id=%s",(raced,))
    assert_rejected(lambda: complete(claimed["job_id"],claimed["claim_token"]))
    result=recover()
    assert result["blocked"]==1,result
    assert job_status(raced_run)=="blocked"
    assert one("SELECT status FROM public.factory_runs WHERE id=%s",(raced_run,))=="specialist_review_failed"
    assert one("SELECT count(*) FROM public.factory_evaluations WHERE run_id=%s",(raced_run,))==0

    # Same-epoch re-claim invalidates an older worker's completion token.
    retries=project("same-epoch-lease")
    retry_run=run(retries)
    enqueue(retry_run)
    first=claim("worker-one")
    assert first["run_id"]==str(retry_run)
    conn.execute("UPDATE public.factory_specialist_lane_jobs SET lease_expires_at=now()-interval '1 minute' WHERE id=%s",(first["job_id"],))
    out=recover()
    assert out["requeued"]==1,out
    second=claim("worker-two")
    assert second["job_id"]==first["job_id"]
    assert second["claim_token"]!=first["claim_token"]
    assert_rejected(lambda: complete(first["job_id"],first["claim_token"]))
    assert complete(second["job_id"],second["claim_token"])["status"]=="passed"
    assert one("SELECT count(*) FROM public.factory_evaluations WHERE run_id=%s",(retry_run,))==1
    assert one("SELECT evidence ? '_factory_claim_token' FROM public.factory_specialist_lane_jobs WHERE id=%s",(second["job_id"],)) is False

    # A held operator-control row on one project must not starve another.
    blocked=project("operator-lock-held")
    blocked_run=run(blocked)
    enqueue(blocked_run)
    free=project("other-project-still-eligible")
    free_run=run(free)
    enqueue(free_run)
    with psycopg.connect(dsn) as pausing:
        pausing.execute("UPDATE public.factory_project_execution_controls SET state='paused' WHERE project_id=%s",(blocked,))
        with psycopg.connect(dsn,autocommit=True) as worker:
            worker.execute("SET statement_timeout='3000ms'")
            got=worker.execute("SELECT public.factory_claim_specialist_lane('security','other-worker',600)").fetchone()[0]
            assert got["run_id"]==str(free_run),got
        pausing.commit()
    assert job_status(blocked_run)=="queued"
    assert complete(got["job_id"],got["claim_token"])["status"]=="passed"

    # Reverse race: once completion owns the shared epoch lock, Pause waits.
    shared=project("transactional-completion")
    shared_run=run(shared)
    enqueue(shared_run)
    receipt=claim("worker-share")
    with psycopg.connect(dsn) as finishing, psycopg.connect(dsn,autocommit=True) as pauser:
        finishing.execute("SELECT public.factory_complete_specialist_lane(%s,'passed','[]'::jsonb,%s::jsonb)",(receipt["job_id"],json.dumps({"_factory_claim_token":receipt["claim_token"]})))
        pauser.execute("SET lock_timeout='200ms'")
        assert_rejected(lambda: pauser.execute(
            "UPDATE public.factory_project_execution_controls SET state='paused' WHERE project_id=%s",(shared,)),"55P03")
        finishing.commit()
        pauser.execute("UPDATE public.factory_project_execution_controls SET state='paused' WHERE project_id=%s",(shared,))
    assert job_status(shared_run)=="passed"
    assert one("SELECT count(*) FROM public.factory_evaluations WHERE run_id=%s",(shared_run,))==1
    assert claim("worker-after-pause") is None

    print("SPECIALIST_EPOCH_POSTGRES_PASS=1")
