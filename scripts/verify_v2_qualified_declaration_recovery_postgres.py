def call(c, *values):
    c.execute("select public.factory_requeue_v2_declaration_preflight_once("
              + ",".join(["%s"]*len(values)) + ")",values)
    return c.fetchone()[0]

def rejected(db, values):
    try:
        with db.transaction():
            with db.cursor() as c:
                call(c,*values)
    except psycopg.Error:
        return
    raise AssertionError("unsafe V2 recovery succeeded")

